"""Иерархия доменных исключений модуля ai_detector.

Наружу из публичного API пробрасывается только эта иерархия (FR-013):
частичных или «мусорных» результатов не возвращается. Сообщения —
человекочитаемые, на русском языке, без токена доступа и без пути
к temp-каталогу в обязательной части (contracts/public-api.md §3).
"""


class AIDetectionError(Exception):
    """Базовое исключение модуля детекции AI-генерации."""


class RepoCloneError(AIDetectionError):
    """Неудачное клонирование репозитория.

    Причины: неверный/несуществующий URL, отсутствие прав (приватный
    репозиторий без токена), сетевой сбой, превышение таймаута клонирования.
    """


class MetadataExtractionError(AIDetectionError):
    """Сбой извлечения метаданных репозитория.

    Причины: ненулевой выход `git log` / `git ls-files`, строка истории
    не распарсилась как JSON (fail-loud, data-model.md §1).
    """


class CodeAggregationError(AIDetectionError):
    """Сбой агрегации исходного кода.

    Причины: ошибка чтения файла, либо ни одного поддерживаемого файла
    в репозитории («no supported source files», edge case, FR-013).
    """


class LLMJudgementError(AIDetectionError):
    """Сбой оценки локальной LLM.

    Причины: LLM недоступна после исчерпания повторов, `parsed is None`
    (ответ не по схеме), 404 (модель/эндпоинт не найден), context overflow
    (объём кода превышает вместимость модели — усечение запрещено, FR-004).
    """
