def format_commit_history(commits: list[CommitInfo]) -> str:
    """Форматирует историю коммитов: по одному коммиту на строку.

    Формат строки: ``<hash[0..7]> | <date ISO> | <author> | <message>``
    (contracts/llm-structured-output.md §4). Пустая история — пустая строка.
    """
    return "\n".join(f"{commit.hash[:7]} | {commit.date} | {commit.author} | {commit.message}" for commit in commits)


def format_file_tree(file_tree: list[str]) -> str:
    """Форматирует дерево файлов: по одному пути (relative posix) на строку."""
    return "\n".join(file_tree)


